export type Lang = keyof typeof STRINGS;

export function resolveLang(locale: string | undefined): Lang {
  const l = (locale ?? "").toLowerCase();
  return l.startsWith("zh") ? "zh" : l.startsWith("en") || l ? "en" : "zh";
}

export type T = typeof STRINGS.zh;

export function stringsFor(locale: string | undefined): T {
  return STRINGS[resolveLang(locale)] as T;
}
